    const [completingTaskId, setCompletingTaskId] = useState<number | null>(null);
    const [editingTask, setEditingTask] = useState<UrgentTask | null>(null);
    const [pendingCompleteTask, setPendingCompleteTask] = useState<UrgentTask | null>(null);
    const [pendingDeleteTask, setPendingDeleteTask] = useState<UrgentTask | null>(null);
    const [deletingTaskId, setDeletingTaskId] = useState<number | null>(null);
    const [itPersonnel, setITPersonnel] = useState<TroubleTicketITPersonnel[]>([]);

    const canCompleteUrgentTask =
        String(authUser?.role_code ?? "")
            .trim()
            .toUpperCase() === "IT_ADMIN";

    async function loadTasks() {
        try {
            setLoading(true);
            setError("");
            const response = await urgentTaskApi.list({
                page: 1,
                limit: 200,
            });
            setTasks(response.data ?? []);
            setTotal(Number(response.total ?? response.data?.length ?? 0));
        } catch (reason) {
            setTasks([]);
            setTotal(0);
            setError(
                reason instanceof Error
                    ? reason.message
                    : "Unable to load urgent tasks."
            );
        } finally {
            setLoading(false);
        }
    }

    useEffect(() => {
        let active = true;

        async function loadActionContext() {
            try {
                const [
                    authResponse,
                    personnelResponse,
                ] = await Promise.all([
                    authApi.me(),
                    dashboardApi.troubleTicketITPersonnel(),
                ]);

                if (!active) {
                    return;
                }

                setAuthUser(
                    authResponse.data ?? null
                );

                setITPersonnel(
                    personnelResponse.data ?? []
                );
            } catch (reason) {
                console.error(
                    "Unable to load urgent-task action context:",
                    reason
                );

                if (active) {
                    setAuthUser(null);
                    setITPersonnel([]);
                }
            }
        }

        void loadActionContext();

        return () => {
            active = false;
        };
    }, []);

    useEffect(() => {
        void loadTasks();
    }, []);

    const filtered = useMemo(() => {
        const q = search.trim().toLowerCase();
        return tasks.filter((item) => {
            const matchSearch =
                !q ||
                item.reference.toLowerCase().includes(q) ||
                item.title.toLowerCase().includes(q) ||
                item.description.toLowerCase().includes(q) ||
                item.assigned_to.toLowerCase().includes(q) ||
                item.assigned_to_name.toLowerCase().includes(q) ||
                item.generated_by_name.toLowerCase().includes(q);

            const matchStatus = !activeStatus || item.status === activeStatus;
            const matchPriority = !activePriority || item.priority === activePriority;
            return matchSearch && matchStatus && matchPriority;
        });
    }, [tasks, search, activeStatus, activePriority]);

    const counts = useMemo(
        () => ({
            total: tasks.length,
            pending: tasks.filter((task) => task.status === "Pending").length,
            inProgress: tasks.filter((task) => task.status === "In Progress").length,
            completed: tasks.filter((task) => task.status === "Completed").length,
        }),
        [tasks]
    );

