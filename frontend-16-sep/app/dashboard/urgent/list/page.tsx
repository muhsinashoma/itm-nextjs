function ActionsDropdown({
    item,
    canManage,
    completing,
    openUp = false,
    onView,
    onUpdate,
    onComplete,
    onDelete,
}: {
    item: UrgentTask;
    canManage: boolean;
    completing: boolean;
    openUp?: boolean;
    onView: () => void;
    onUpdate: () => void;
    onComplete: () => void;
    onDelete: () => void;
}) {
    const [open, setOpen] =
        useState(false);

    const ref =
        useRef<HTMLDivElement>(null);

    useEffect(() => {
        const handler = (
            event: MouseEvent
        ) => {
            if (
                ref.current &&
                !ref.current.contains(
                    event.target as Node
                )
            ) {
                setOpen(false);
            }
        };

        document.addEventListener(
            "mousedown",
            handler
        );

        return () =>
            document.removeEventListener(
                "mousedown",
                handler
            );
    }, []);

    const isCompleted =
        item.status === "Completed";

    return (
        <div
            ref={ref}
            className="relative inline-block"
        >
            <button
                type="button"
                onClick={() =>
                    setOpen(!open)
                }
                className="flex items-center gap-1 rounded-lg border border-border bg-muted px-2 py-1 text-[9.5px] font-medium text-foreground transition hover:bg-border"
            >
                Actions
                <ChevronDown size={11} />
            </button>

            {open && (
                <div
                    className={`absolute right-0 z-[80] w-44 overflow-hidden rounded-xl border border-border bg-card py-1 shadow-xl ${openUp
                        ? "bottom-full mb-1"
                        : "top-full mt-1"
                        }`}
                >
                    <DropItem
                        icon={<Eye size={12} />}
                        label="View"
                        color="text-blue-600"
                        onClick={() => {
                            onView();
                            setOpen(false);
                        }}
                    />

                    {canManage &&
                        !isCompleted && (
                            <DropItem
                                icon={
                                    <Pencil
                                        size={12}
                                    />
                                }
                                label="Update"
                                color="text-violet-700"
                                onClick={() => {
                                    onUpdate();
                                    setOpen(false);
                                }}
                            />
                        )}

                    {canManage &&
                        !isCompleted && (
                            <DropItem
                                icon={
                                    completing ? (
                                        <Loader2
                                            size={12}
                                            className="animate-spin"
                                        />
                                    ) : (
                                        <CheckCircle2
                                            size={12}
                                        />
                                    )
                                }
                                label={
                                    completing
                                        ? "Completing..."
                                        : "Completed"
                                }
                                color="text-emerald-700"
                                disabled={
                                    completing
                                }
                                onClick={() => {
                                    if (
                                        completing
                                    ) {
                                        return;
                                    }

                                    onComplete();
                                    setOpen(false);
                                }}
                            />
                        )}

                    {/* {!isCompleted && (
                        <DropItem
                            icon={
                                <Trash2
                                    size={12}
                                />
                            }
                            label="Delete"
                            color="text-red-600"
                            onClick={() => {
                                onDelete();
                                setOpen(false);
                            }}
                        />
                    )} */}
                </div>
            )}
        </div>
    );
}

